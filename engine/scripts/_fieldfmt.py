#!/usr/bin/env python3
"""
_fieldfmt.py — рендер значения профиля в ТОЧНУЮ строку ячейки листа формы.

Зачем отдельный модуль. Реестр объявляет `type` у каждого поля, но до этого
модуля движок его не читал: дата уходила в испанский бланк как `1996-03-14`
вместо `14/03/1996`, а `Tipo de autorización` (`type: checkbox`) рендерился
текстом вместо отметки галочки. Спека агента (`.claude/agents/field-qa-reviewer.md`)
предписывала «дата DD/MM/AAAA» давно — код отставал.

Почему не в `chat/_common.py`: тот модуль про защиту от НЕДОВЕРЕННОГО ввода
(лимиты, containment путей, соль). Рендер ячейки формы — другой домен.

КРИТИЧЕСКИЙ ИНВАРИАНТ. `fill_forms.fill_form()` пишет значение, а
`field_qa.rederive_expected()` НЕЗАВИСИМО выводит ожидаемое из того же профиля;
`field_qa.diff()` их сличает. Если две стороны отформатируют по-разному, каждое
форматированное поле станет `WRONG: не совпадает` и уронит exit-код. Поэтому
трансформация живёт ЗДЕСЬ, в одной функции, и точек вызова ровно две. Не
инлайньте её обратно и не заводите второй форматтер.
"""

from __future__ import annotations

import re

# Ровно ISO-календарная дата, ничего больше.
#
# ПОЧЕМУ РЕГУЛЯРКА, А НЕ `date.fromisoformat`: начиная с Python 3.11 та
# принимает существенно более широкую грамматику (`20260727`, `2026-W30-1`,
# полные timestamp'ы с временем и часовым поясом). С ней строка в
# закоммиченных артефактах примера стала бы функцией версии интерпретатора, и
# `git status` после пересборки зеленел бы или краснел в зависимости от того,
# на чём её запустили. Здесь нужна не «разбери дату», а «распознай ровно ту
# форму, которую пишет интейк». Не «упрощайте» это до fromisoformat.
_ISO_DATE = re.compile(r"^(\d{4})-(\d{2})-(\d{2})$")


def render_value(val, field: dict) -> str:
    """НЕПУСТОЕ значение профиля -> точная строка ячейки листа.

    Единственное место трансформации: `fill_forms` её пишет, `field_qa` ею же
    ре-деривирует ожидаемое. Идемпотентна, тотальна (нераспознанное проходит
    насквозь), отсутствующий `type` -> `str(val)` = прежнее поведение.

    Правила v1:
      * `type: date`   — `AAAA-MM-DD` -> `DD/MM/AAAA`; всё прочее проходит
        насквозь, чем и обеспечена идемпотентность: уже отформатированная
        `14/03/1996` под ISO-регулярку не подходит и возвращается как есть, так
        что второй прогон не переставляет части даты. Диапазоны, «примерно» и
        частичные даты — тоже насквозь.
        Форматтер — ПРЕЗЕНТЕР, а не валидатор: он не судит о корректности даты
        и не делает `strip()`. Мусор в профиле должен доехать до листа мусором
        и быть пойманным глазами, а не тихо нормализоваться.
      * `type: checkbox` И `domain: fixed_checked` — `☑ отметить — <значение>`.
        Тик ПЛЮС значение профиля, а не константа: константа схлопнула бы
        разные `permit_type` в одну ячейку и убила бы детекцию подмены
        (enum-проверки на `fixed_checked` нет — это директива рендера, а не
        словарь ввода, и в `controlled_vocabularies` ему делать нечего).
      * `type: number` в v1 НЕ трогаем — это сдвинуло бы уже закоммиченные
        значения и требует отдельного решения про разделитель разрядов и
        символ валюты (`1234.5` -> `1.234,50 €`?). Числа проходят насквозь.

    Правило завязано на FIELD, а не на profile_key: `applicant.permit_type`
    используется дважды — чекбоксом в `MI-T` и текстом в `memoria`, — и один
    ключ обязан рендериться двумя способами.
    """
    ftype = field.get("type", "text")

    if ftype == "date":
        s = str(val)
        m = _ISO_DATE.match(s)
        if m:
            y, mo, d = m.groups()
            return f"{d}/{mo}/{y}"
        return s  # включая уже-DD/MM/AAAA (_ES_DATE) и всё нераспознанное

    if ftype == "checkbox" and field.get("domain") == "fixed_checked":
        return f"☑ отметить — {val}"

    return str(val)
